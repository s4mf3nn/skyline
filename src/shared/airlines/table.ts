import type { Airline, TailPalette } from "./types";

// Dérive de la compagnie inconnue, partagée (et gelée) par les compagnies sans palette du handoff.
const UNKNOWN_TAIL: TailPalette = Object.freeze({
  base: "#CFC8BA",
  stripe1: "#1D1D1B",
  stripe2: null,
  disc: null,
});

/** Entrée `xx` du handoff, utilisée quand aucune compagnie n'est reconnue. */
export const UNKNOWN_AIRLINE: Airline = {
  code: "xx",
  name: "Inconnue",
  country: "France",
  primary: "#1D1D1B",
  secondary: "#F2E8D5",
  iata: [],
  icao: [],
  tail: UNKNOWN_TAIL,
};

// Compagnie du catalogue sans couleurs du handoff : le propriétaire les renseignera plus tard (INV8 : rien d'inventé).
function catalogOnly(name: string, iata: readonly string[], icao: readonly string[]): Airline {
  return {
    code: icao[0] as string,
    name,
    country: null,
    primary: UNKNOWN_AIRLINE.primary,
    secondary: UNKNOWN_AIRLINE.secondary,
    iata,
    icao,
    tail: UNKNOWN_TAIL,
  };
}

